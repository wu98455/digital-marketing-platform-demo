/** 扁平为 Select options：value 为标签名 */
export function catalogTagOptions(catalog: TagGroup[]) {
  return catalog.flatMap((g) =>
    g.tags.map((tag) => ({ label: `${g.group} / ${tag}`, value: tag })),
  );
}
